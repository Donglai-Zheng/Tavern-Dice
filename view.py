def dim_table(ui):
    """Darken existing shapes directly for overlays, without an image library."""
    canvas = ui["canvas"]
    for item in canvas.find_all():
        colour = canvas.itemcget(item, "fill")
        if colour.startswith("#"):
            canvas.itemconfigure(item, fill=blend(colour, "#160f0b", 0.48))
        if canvas.type(item) in ("polygon", "rectangle", "oval"):
            outline = canvas.itemcget(item, "outline")
            if outline.startswith("#"):
                canvas.itemconfigure(item, outline=blend(outline, "#160f0b", 0.48))
    for item in ui["buttons"]:
        if item["fill"]:
            item["fill"] = blend(item["fill"], "#160f0b", 0.48)


def draw_game(game, ui):
    """Draw scores, dice and controls for the current game phase.

    Rolling faces are display effects only; the actual values stay in game.
    Only available dice receive click areas, and valid selections enable
    scoring controls. Draw event feedback above the table when needed.
    """
    phase = game["phase"]
    canvas = ui["canvas"]
    for i, x in enumerate((64, 674)):
        label(ui, x, 51, "Player " + str(i + 1), 24, anchor="w", title=True)
        label(ui, x + 138, 51, str(game["scores"][i]), 24, anchor="w", tag="score" + str(i))
        if game["player"] == i:
            canvas.create_line(x, 76, x + 97, 76, fill=COLOURS["gold"], width=3)
    label(ui, 480, 49, "Target " + str(game["target"]), 20, "muted")
    label(ui, 64, 98, "Banked", 13, "muted", anchor="w")
    label(ui, 674, 98, "Banked", 13, "muted", anchor="w")

    values = game["dice"] + game["kept"]
    available = len(game["dice"])
    if phase in ("transition", "ready"):
        values = game["last_dice"] or [None] * 6
        available = 0
    for i in range(6):
        x, y, angle, lift = 180 + i * 120, 280, 0, 0
        value = values[i]
        kept = i >= available and value is not None
        if phase == "rolling" and i < available:
            frame = ui["frame"] or 0
            progress = frame / 24
            decay = (1 - progress) ** 1.6
            x += 23 * math.sin(frame * 0.55 + i) * decay
            lift = 34 * abs(math.sin(progress * math.pi * 3 + i * 0.2)) * decay
            angle = 32 * math.sin(frame * 0.65 + i * 1.3) * decay
            value = (game["dice"][i] + frame // 2 + i) % 6 + 1
        selected = phase == "selecting" and i in game["selected"]
        draw_die(ui, x, y, value, selected=selected, kept=kept, angle=angle, lift=lift)
        if phase == "selecting" and i < available:
            ui["dice_boxes"].append((i, (x - 48, y - 52, x + 48, y + 55)))
        elif i >= len(game["dice"]) and game["kept"] and phase not in ("ready", "transition"):
            label(ui, x, 345, "KEPT", 12, "muted")

    selected_values = [game["dice"][i] for i in game["selected"]]
    score = score_selection(selected_values)
    label(ui, 480, 392, "Turn " + str(game["turn_score"]) + "   +   Selected " + str(score), 23)
    hint = game["message"] or "Choose scoring dice. Turn points are not banked yet."
    hint_colour = "muted"
    if phase == "selecting" and game["selected"]:
        if score == 0:
            hint, hint_colour = "Invalid combination. Every selected die must score.", "red"
        else:
            remaining = len(game["dice"]) - len(game["selected"])
            hint = "Keep this selection and roll " + str(remaining or 6) + ", or bank and end your turn."
    elif phase == "rolling":
        hint = "Rolling…"
    elif phase == "settling":
        hint = "No scoring dice in this roll."
    elif phase in ("banking", "bust", "transition"):
        hint = ""
    label(ui, 480, 426, hint, 16, hint_colour, tag="hint")
    enabled = phase == "selecting" and score > 0
    roll_text = "Roll 6 Dice" if phase == "ready" else "Roll Again"
    if phase == "rolling":
        roll_text = "Rolling…"
    bank_text = "Bank Points" + (" · " + str(game["turn_score"] + score) if enabled else "")
    button(ui, "roll", 336, 491, 254, roll_text, ui["actions"]["roll"], enabled=enabled or phase == "ready")
    button(ui, "bank", 624, 491, 254, bank_text, ui["actions"]["bank"], primary=True, enabled=enabled)
    link(ui, "request_menu", 55, 563, "Menu", ui["actions"]["request_menu"])
    link(ui, "rules", 902, 563, "Rules", ui["actions"]["rules"])
    if ui["screen"] == "confirm":
        dim_table(ui)
        ui["buttons"] = []
        ui["dice_boxes"] = []
        label(ui, 480, 172, "Leave this match?", 43, "gold", title=True)
        label(ui, 480, 218, "This match will be cleared.", 20)
        button(ui, "back", 336, 489, 254, "Keep playing", ui["actions"]["back"], primary=True)
        button(ui, "menu", 624, 489, 254, "Main Menu", ui["actions"]["menu"])
    elif phase == "bust":
        dim_table(ui)
        label(ui, 480 + ui["shake"], 158, "BUST!", 74, "red", title=True, tag="bust")
        label(ui, 480, 214, str(game["lost"]) + " turn points lost", 25)
        label(ui, 480, 544, "Player " + str(2 - game["player"]) + " is next…", 20)
    elif phase == "transition":
        dim_table(ui)
        label(ui, 480, 174, "Player " + str(game["player"] + 1) + "'s turn", 44, "gold", title=True)
        label(ui, 480, 221, "Get ready to roll.", 21)
    elif phase == "banking":
        label(ui, 480, 162, "+" + str(game["banked"]) + " banked", 38, "gold", title=True)
        label(ui, 480, 207, "Your points are safe.", 18, "muted")


