def render(game, ui):
    """Rebuild the current screen and its click areas from the saved state.

    Destroy the previous entry widget before redrawing so it cannot remain
    visible or receive input on another screen.
    """
    if ui.get("entry") is not None:
        ui["entry"].destroy()
        ui["entry"] = None
    ui["canvas"].delete("all")
    ui.update(buttons=[], dice_boxes=[], hover=None, focus=None)
    background(ui)
    screen = ui["screen"]
    if screen == "menu":
        draw_menu(ui)
    elif screen == "setup":
        draw_setup(ui)
    elif screen == "rules":
        draw_rules(ui)
    elif screen == "victory":
        draw_victory(game, ui)
    else:
        draw_game(game, ui)


def contains(bounds, x, y):
    x1, y1, x2, y2 = bounds
    return x1 <= x <= x2 and y1 <= y <= y2


def pointer_click(ui, event):
    """Dispatch a click to an enabled button or an available die's action."""
    for item in ui["buttons"]:
        if item["enabled"] and contains(item["bounds"], event.x, event.y):
            item["action"]()
            return
    for index, bounds in ui["dice_boxes"]:
        if contains(bounds, event.x, event.y):
            ui["actions"]["die"](index)
            return


def highlight_buttons(ui):
    """Update button styling for mouse hover and keyboard focus."""
    for item in ui["buttons"]:
        active = item["enabled"] and item["key"] in (ui.get("hover"), ui.get("focus"))
        if item["shape"] is not None:
            fill = item["fill"]
            if active:
                fill = COLOURS["gold_hover"] if item["primary"] else "#4b3525"
            ui["canvas"].itemconfigure(item["shape"], fill=fill, width=2 if active else 1)


def pointer_move(ui, event):
    hovered = None
    for item in ui["buttons"]:
        if item["enabled"] and contains(item["bounds"], event.x, event.y):
            hovered = item["key"]
            break
    over_die = any(contains(bounds, event.x, event.y) for _, bounds in ui["dice_boxes"])
    ui["canvas"].configure(cursor="hand2" if hovered or over_die else "")
    if hovered != ui.get("hover"):
        ui["hover"] = hovered
        highlight_buttons(ui)


def focus_next(ui, event):
    """Move keyboard focus through enabled buttons; Shift reverses direction."""
    keys = [item["key"] for item in ui["buttons"] if item["enabled"]]
    if not keys:
        return "break"
    step = -1 if event.state & 1 else 1
    position = keys.index(ui["focus"]) if ui.get("focus") in keys else (-1 if step == 1 else 0)
    ui["focus"] = keys[(position + step) % len(keys)]
    ui["canvas"].focus_set()
    highlight_buttons(ui)
    return "break"


def activate_focused(ui, event):
    for item in ui["buttons"]:
        if item["key"] == ui.get("focus") and item["enabled"]:
            item["action"]()
            return "break"


def build_canvas(ui):
    """Create the Canvas, choose available fonts and bind input handlers."""
    families = set(font.families(ui["window"]))
    ui["title_font"] = "Georgia" if "Georgia" in families else "Times"
    ui["body_font"] = "Arial" if "Arial" in families else "Helvetica"
    canvas = tk.Canvas(ui["window"], width=960, height=600, highlightthickness=0)
    canvas.pack(fill="both", expand=True)
    ui["canvas"] = canvas
    canvas.bind("<Button-1>", functools.partial(pointer_click, ui))
    canvas.bind("<Motion>", functools.partial(pointer_move, ui))
    ui["window"].bind("<Tab>", functools.partial(focus_next, ui))
    ui["window"].bind("<ISO_Left_Tab>", functools.partial(focus_next, ui))
    ui["window"].bind("<Return>", functools.partial(activate_focused, ui))
    ui["window"].bind("<space>", functools.partial(activate_focused, ui))
