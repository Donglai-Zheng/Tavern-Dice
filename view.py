COLOURS = {
    "background": "#2b1d16", "wood": "#38271d", "ivory": "#f1e5ce",
    "gold": "#c7a260", "gold_hover": "#dbb97a", "muted": "#b5a18a",
    "red": "#d88370", "ink": "#35261d", "edge": "#8b7150",
    "disabled": "#78634f", "kept": "#a5967e"
}
PIPS = {
    1: [(1, 1)], 2: [(0, 0), (2, 2)],
    3: [(0, 0), (1, 1), (2, 2)],
    4: [(0, 0), (2, 0), (0, 2), (2, 2)],
    5: [(0, 0), (2, 0), (1, 1), (0, 2), (2, 2)],
    6: [(0, 0), (2, 0), (0, 1), (2, 1), (0, 2), (2, 2)]
}


def blend(first, second, amount):
    """Mix two hex colours; amount from 0 to 1 controls the second colour."""
    channels = []
    for start in (1, 3, 5):
        a = int(first[start:start + 2], 16)
        b = int(second[start:start + 2], 16)
        channels.append(round(a * (1 - amount) + b * amount))
    return "#{:02x}{:02x}{:02x}".format(*channels)


def label(ui, x, y, text, size=20, colour="ivory", anchor="center", title=False, tag=""):
    family = ui["title_font"] if title else ui["body_font"]
    return ui["canvas"].create_text(
        x, y, text=text, font=(family, -size), fill=COLOURS.get(colour, colour),
        anchor=anchor, tags=tag
    )


def rounded_box(canvas, x1, y1, x2, y2, radius, **options):
    points = [x1 + radius, y1, x2 - radius, y1, x2, y1, x2, y1 + radius,
              x2, y2 - radius, x2, y2, x2 - radius, y2, x1 + radius, y2,
              x1, y2, x1, y2 - radius, x1, y1 + radius, x1, y1]
    return canvas.create_polygon(points, smooth=True, splinesteps=16, **options)


def background(ui):
    """Draw a warm background and subtle wood grain without random numbers."""
    canvas = ui["canvas"]
    for y in range(0, 600, 6):
        warmth = 0.55 * math.sin(math.pi * y / 600)
        colour = blend(COLOURS["background"], "#503a28", warmth)
        canvas.create_rectangle(0, y, 960, y + 6, fill=colour, outline="")
    for row in range(6, 600, 11):
        points = []
        for x in range(-20, 981, 40):
            points.extend((x, row + 2 * math.sin(x / 95 + row)))
        shade = blend(COLOURS["background"], "#503a28",
                      0.55 * math.sin(math.pi * row / 600) + 0.06)
        canvas.create_line(points, fill=shade, smooth=True, width=1)


def button(ui, key, x, y, width, text, action, primary=False, enabled=True, small=False):
    """Draw a button and record its bounds, enabled state and action together."""
    height = 44 if small else 54
    fill = COLOURS["gold"] if primary else COLOURS["background"]
    fg = "ink" if primary else "ivory"
    if not enabled:
        fill, fg = COLOURS["wood"], "disabled"
    bounds = (x - width / 2, y - height / 2, x + width / 2, y + height / 2)
    shape = rounded_box(ui["canvas"], *bounds, 9, fill=fill,
                        outline=COLOURS["edge"] if enabled else COLOURS["wood"], width=1)
    text_id = label(ui, x, y, text, 18 if small else 22, fg)
    ui["buttons"].append({"key": key, "bounds": bounds, "action": action,
                          "enabled": enabled, "shape": shape, "fill": fill,
                          "primary": primary, "text": text_id})


def link(ui, key, x, y, text, action):
    text_id = label(ui, x, y, text, 17, "muted")
    ui["buttons"].append({"key": key, "bounds": (x - 38, y - 22, x + 38, y + 22),
                          "action": action, "enabled": True, "shape": None,
                          "fill": "", "primary": False, "text": text_id})


def draw_die(ui, x, y, value, size=88, selected=False, kept=False, angle=0, lift=0):
    """Draw a die with selection or kept styling; None displays a question mark.

    Rotate the face and pips together. Keep its shadow on the table while
    lifting the face to give the rolling animation a bouncing effect.
    """
    canvas = ui["canvas"]
    half = size / 2
    canvas.create_oval(x - half - 2, y + half - 1, x + half + 3, y + half + 14,
                       fill="#241811", outline="")
    center_y = y - lift - (5 if selected else 0)
    radians = math.radians(angle)

    def rotate(dx, dy, depth=0):
        return (x + dx * math.cos(radians) - dy * math.sin(radians),
                center_y + dx * math.sin(radians) + dy * math.cos(radians) + depth)

    def face(extra=0, depth=0, **options):
        h = half + extra
        r = size * 0.1
        corners = [(-h + r, -h), (h - r, -h), (h, -h), (h, -h + r),
                   (h, h - r), (h, h), (h - r, h), (-h + r, h),
                   (-h, h), (-h, h - r), (-h, -h + r), (-h, -h)]
        points = []
        for dx, dy in corners:
            points.extend(rotate(dx, dy, depth))
        canvas.create_polygon(points, smooth=True, splinesteps=12, **options)

    if selected:
        face(extra=5, depth=2, fill="", outline=COLOURS["gold"], width=2)
    face(depth=7, fill="#81705a" if kept else "#bca887", outline="")
    face(fill=COLOURS["kept"] if kept else COLOURS["ivory"],
         outline="#c5b798" if kept else "#fff1d8", width=1)
    if value is None:
        label(ui, x, center_y, "?", int(size * 0.42), "edge", title=True)
    else:
        radius = size * 0.067
        for column, row in PIPS[value]:
            px, py = rotate((column - 1) * size * 0.245, (row - 1) * size * 0.245)
            canvas.create_oval(px - radius, py - radius, px + radius, py + radius,
                               fill=COLOURS["ink"], outline="")


